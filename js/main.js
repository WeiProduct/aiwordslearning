// ===== Review-schedule simulator =====
const SCHED_STEPS = [0, 1, 3, 7, 15, 30];
let schedIdx = 1;

function renderSched() {
  const tl = document.getElementById('schedTimeline');
  if (!tl) return;
  Array.from(tl.children).forEach((node, i) => {
    node.classList.toggle('active', i === schedIdx);
    node.classList.toggle('done', i < schedIdx);
  });
  const val = document.getElementById('schedNextVal');
  if (val) val.textContent = I18N[currentLang]['schedV' + SCHED_STEPS[schedIdx]];
}

function initSched() {
  const tl = document.getElementById('schedTimeline');
  if (!tl) return;
  const know = document.getElementById('schedKnow');
  const fuzzy = document.getElementById('schedFuzzy');
  const reset = document.getElementById('schedReset');
  if (know) know.addEventListener('click', () => { schedIdx = Math.min(schedIdx + 1, SCHED_STEPS.length - 1); renderSched(); });
  if (fuzzy) fuzzy.addEventListener('click', () => { schedIdx = Math.max(schedIdx - 1, 1); renderSched(); });
  if (reset) reset.addEventListener('click', () => { schedIdx = 1; renderSched(); });
  renderSched();
}

// ===== Count-up stats =====
function initCounters() {
  const els = document.querySelectorAll('[data-count]');
  if (!els.length) return;
  const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const fmt = (n, suf) => Number(Math.round(n)).toLocaleString('en-US') + suf;
  const run = (el) => {
    const target = parseFloat(el.getAttribute('data-count'));
    const suf = el.getAttribute('data-suffix') || '';
    if (reduce || target === 0) { el.textContent = fmt(target, suf); return; }
    const dur = 1400, start = performance.now();
    const tick = (now) => {
      const p = Math.min((now - start) / dur, 1);
      const eased = 1 - Math.pow(1 - p, 3);
      el.textContent = fmt(target * eased, suf);
      if (p < 1) requestAnimationFrame(tick);
    };
    requestAnimationFrame(tick);
  };
  if (!('IntersectionObserver' in window)) { els.forEach(run); return; }
  const io = new IntersectionObserver((ents) => {
    ents.forEach(e => { if (e.isIntersecting) { run(e.target); io.unobserve(e.target); } });
  }, { threshold: 0.5 });
  els.forEach(el => io.observe(el));
}

// ===== Forgetting-curve stroke animation =====
function initCurve() {
  const paths = document.querySelectorAll('.curve-anim');
  const svg = document.getElementById('curveSvg');
  if (!paths.length || !svg) return;
  const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  paths.forEach(p => {
    const len = p.getTotalLength();
    p.style.strokeDasharray = len;
    p.style.strokeDashoffset = reduce ? 0 : len;
  });
  if (reduce) return;
  const io = new IntersectionObserver((ents) => {
    ents.forEach(e => {
      if (e.isIntersecting) {
        paths.forEach((p, i) => {
          p.style.transition = 'stroke-dashoffset 1.8s ease ' + (i * 0.4) + 's';
          p.style.strokeDashoffset = 0;
        });
        io.disconnect();
      }
    });
  }, { threshold: 0.35 });
  io.observe(svg);
}

// ===== Gallery =====
function initGallery() {
  const track = document.getElementById('galTrack');
  if (!track) return;
  const shots = Array.from(track.children);
  const dotsWrap = document.getElementById('galDots');
  const prev = document.getElementById('galPrev');
  const next = document.getElementById('galNext');

  shots.forEach((_, i) => {
    const b = document.createElement('button');
    b.type = 'button';
    b.setAttribute('aria-label', 'screenshot ' + (i + 1));
    if (i === 0) b.classList.add('active');
    b.addEventListener('click', () => shots[i].scrollIntoView({ behavior: 'smooth', inline: 'center', block: 'nearest' }));
    dotsWrap.appendChild(b);
  });
  const dots = Array.from(dotsWrap.children);

  function activeIndex() {
    const c = track.scrollLeft + track.clientWidth / 2;
    let best = 0, bd = Infinity;
    shots.forEach((s, i) => {
      const center = s.offsetLeft + s.offsetWidth / 2;
      const d = Math.abs(center - c);
      if (d < bd) { bd = d; best = i; }
    });
    return best;
  }
  track.addEventListener('scroll', () => {
    const i = activeIndex();
    dots.forEach((d, j) => d.classList.toggle('active', j === i));
  }, { passive: true });

  const step = () => (shots[1] ? shots[1].offsetLeft - shots[0].offsetLeft : 300);
  if (prev) prev.addEventListener('click', () => track.scrollBy({ left: -step(), behavior: 'smooth' }));
  if (next) next.addEventListener('click', () => track.scrollBy({ left: step(), behavior: 'smooth' }));

  // Lightbox
  const lb = document.createElement('div');
  lb.className = 'lightbox';
  lb.innerHTML = '<button class="lightbox-close" aria-label="close">&times;</button><img alt="">';
  document.body.appendChild(lb);
  const lbImg = lb.querySelector('img');
  const close = () => lb.classList.remove('open');
  lb.addEventListener('click', e => { if (e.target === lb || e.target.classList.contains('lightbox-close')) close(); });
  document.addEventListener('keydown', e => { if (e.key === 'Escape') close(); });
  track.querySelectorAll('.phone').forEach(p => {
    p.addEventListener('click', () => {
      const img = p.querySelector('img');
      lbImg.src = img.src; lbImg.alt = img.alt;
      lb.classList.add('open');
    });
  });
}

// ===== Scroll reveal =====
function initReveal() {
  const els = document.querySelectorAll('.reveal');
  if (!('IntersectionObserver' in window)) { els.forEach(e => e.classList.add('in')); return; }
  const io = new IntersectionObserver((entries) => {
    entries.forEach(en => {
      if (en.isIntersecting) { en.target.classList.add('in'); io.unobserve(en.target); }
    });
  }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });
  els.forEach((el, i) => { el.style.transitionDelay = (Math.min(i, 6) * 0.05) + 's'; io.observe(el); });
}

// ===== Nav + sticky =====
function initScroll() {
  const nav = document.getElementById('navbar');
  const sticky = document.getElementById('stickyCta');
  const prog = document.getElementById('scrollProgress');
  const onScroll = () => {
    const y = window.scrollY;
    if (nav) nav.classList.toggle('scrolled', y > 20);
    if (sticky) sticky.classList.toggle('show', y > 620);
    if (prog) {
      const h = document.documentElement.scrollHeight - window.innerHeight;
      prog.style.width = (h > 0 ? Math.min(y / h * 100, 100) : 0) + '%';
    }
  };
  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();
}

